import { rootSeed } from '@inertialref/procedural'
import { describe, expect, it } from 'vitest'
import { DISORT_MIE } from './addingDoubling.fixtures.ts'
import { firstOrder, scatteringCosine, solveSlab } from './addingDoubling.ts'
import { henyeyGreensteinMoments, phaseOf } from './legendre.ts'
import { exactPhase } from './moments.ts'
import {
  BATCHES,
  BATCH_CHI_LIMIT,
  acceptRow,
  batchRange,
  combineBatches,
  phaseTable,
  traceBatch,
  traceRow,
  type SlabTrace,
  type TraceBatch,
} from './monteCarloSlab.ts'
import { inDomain, scatteringAngle } from './slabTables.ts'

/*
 * The two references are held to each other here, at a size the gate can
 * afford: a few thousand paths a direction, so the bound is mostly the
 * Monte Carlo's own error. The committed rows, at two hundred thousand
 * paths, are held by `slabTables.test.ts`, and one is regenerated by the
 * slow suite.
 */

const seed = rootSeed('slab')

/** The oracle's stream convergence, which the bound allows beside the sampling error. */
const ORACLE = 0.005

describe('the phase table', () => {
  const moments = Float64Array.from(DISORT_MIE.moments)
  const table = phaseTable(moments, { half: 2048 })

  it('is a distribution over the sphere, and holds the series at its nodes', () => {
    expect(table.cumulative[table.cumulative.length - 1]).toBe(1)
    let total = 0
    for (let k = 0; k < 2 * table.half; k += 1) {
      const j = k % table.half
      expect(table.density[k]!).toBeGreaterThan(0)
      total += table.density[k]! * 4 * Math.PI * table.step ** 2 * (2 * j + 1)
    }
    expect(total).toBeCloseTo(1, 12)
    const disk = exactPhase(moments)
    for (const j of [0, 7, 400, 2048]) {
      const cosine = 1 - 2 * (j * table.step) ** 2
      expect(table.value[j]).toBe(disk(cosine))
      expect(table.value[table.half + 1 + j]).toBe(disk(-cosine))
    }
  })

  it('puts over half of a droplet’s light inside the ten degrees of a lobe, and a tenth of Henyey–Greenstein’s', () => {
    expect(table.lobeShare).toBeGreaterThan(0.5)
    expect(table.lobeShare).toBeLessThan(0.6)
    const smooth = phaseTable(henyeyGreensteinMoments(0.75, 200), {
      half: 2048,
    })
    expect(smooth.lobeShare).toBeGreaterThan(0.1)
    expect(smooth.lobeShare).toBeLessThan(0.25)
    expect(table.coreBins).toBeLessThan(table.lobeBins)
  })

  it('refuses a phase function that is under zero anywhere', () => {
    // First order alone, at g = 2: p(180°) is −1/(4π)… a medium no walk can sample.
    expect(() => phaseTable(Float64Array.of(1, 2), { half: 64 })).toThrow(
      /under zero/,
    )
  })
})

describe('a traced row', () => {
  const smooth = phaseTable(henyeyGreensteinMoments(0.75, 200), {
    half: 4096,
    sun: 0,
  })
  const trace: SlabTrace = {
    depth: 2,
    suns: [1, 0.5],
    viewMu: 0.6,
    azimuth: 45,
    side: 'reflected',
    seed,
  }

  it('is the same row however its batches are run', () => {
    const paths = 4000
    const whole = traceRow(smooth, trace, paths)
    // Last batch first, each alone: a run split over processes.
    const apart: TraceBatch[] = []
    for (let batch = BATCHES - 1; batch >= 0; batch -= 1)
      apart[batch] = traceBatch(smooth, trace, ...batchRange(paths, batch))
    const again = combineBatches(apart)
    expect(again.mean).toEqual(whole.mean)
    expect(again.error).toEqual(whole.error)
    expect(whole.paths).toBe(paths)
    // And another seed is another row.
    const other = traceRow(smooth, { ...trace, seed: rootSeed('other') }, paths)
    expect(other.mean[0]).not.toBe(whole.mean[0])
  })

  it('is first order’s closed form in a slab too thin to scatter twice', () => {
    const thin = traceRow(smooth, { ...trace, depth: 0.01 }, 4000)
    trace.suns.forEach((sun, s) => {
      const cosine = scatteringCosine(sun, 0.6, Math.PI / 4, 'reflected')
      const exact =
        phaseOf(henyeyGreensteinMoments(0.75, 200), cosine) *
        firstOrder(0.01, sun, 0.6, 'reflected')
      // Second order is τ/μ of first, 5% at the lower sun; the sampling error is beside it.
      expect(Math.abs(thin.mean[s]! - exact)).toBeLessThan(
        3 * thin.error[s]! + 0.06 * exact,
      )
    })
  })

  it('is the oracle’s radiance on a Henyey–Greenstein slab, both faces', () => {
    const oracle = solveSlab({
      medium: { moments: henyeyGreensteinMoments(0.75, 200) },
      depths: [2],
      suns: trace.suns,
      views: [0.6],
      azimuths: [45],
      streams: 32,
    })
    for (const side of ['reflected', 'transmitted'] as const) {
      const row = traceRow(smooth, { ...trace, side }, 6000)
      trace.suns.forEach((_, s) =>
        expect(Math.abs(row.mean[s]! - oracle[side][s]!)).toBeLessThan(
          3 * row.error[s]! + ORACLE * oracle[side][s]!,
        ),
      )
    }
  })

  it('is refused when its batch means are not consistent with its error', () => {
    const batch = (mean: number): TraceBatch => ({
      paths: 1000,
      sum: Float64Array.of(1000 * mean),
      // A variance of 0.01 a path: a batch mean's error is 0.003.
      squares: Float64Array.of(1000 * (mean * mean + 0.01)),
    })
    const steady = combineBatches(
      Array.from({ length: BATCHES }, (_, b) => batch(1 + 0.002 * (b % 3))),
    )
    expect(Math.max(...steady.chi)).toBeLessThan(BATCH_CHI_LIMIT)
    expect(acceptRow(steady)).toBe(steady)
    // One batch drew the rare path the other fifteen did not.
    const tailed = combineBatches(
      Array.from({ length: BATCHES }, (_, b) => batch(b === 5 ? 1.05 : 1)),
    )
    expect(() => acceptRow(tailed)).toThrow(/refused/)
  })
})

describe('the true medium at τ = 5', () => {
  it('is within 3·SE + 0.5% of adding-doubling at twelve views, under three suns, over the domain', () => {
    const moments = Float64Array.from(DISORT_MIE.moments)
    const table = phaseTable(moments)
    const suns = [1, 0.5, 0.2]
    const cosines = [0.2, 0.6, 1]
    const azimuths = [0, 90, 180]
    const oracle = solveSlab({
      medium: { moments, phase: exactPhase(moments) },
      depths: [5],
      suns,
      views: cosines,
      azimuths,
      streams: 64,
    })
    // Four cosine–azimuth pairs a face, three faces' worth: twelve views.
    const views = [
      [0.6, 0, 'reflected'],
      [0.6, 90, 'reflected'],
      [0.2, 90, 'reflected'],
      [0.2, 180, 'reflected'],
      [1, 90, 'reflected'],
      [0.6, 180, 'reflected'],
      [0.6, 0, 'transmitted'],
      [0.6, 90, 'transmitted'],
      [0.2, 90, 'transmitted'],
      [0.2, 180, 'transmitted'],
      [1, 90, 'transmitted'],
      [0.6, 180, 'transmitted'],
    ] as const
    let checked = 0
    for (const [viewMu, azimuth, side] of views) {
      const row = traceRow(
        table,
        { depth: 5, suns, viewMu, azimuth, side, seed },
        6000,
      )
      suns.forEach((sun, s) => {
        // The glory, the cloudbow and the forward cone are not the
        // oracle's to answer: it has smoothed whatever scattered twice.
        if (!inDomain(side, scatteringAngle(sun, viewMu, azimuth, side))) return
        const at =
          (s * cosines.length + cosines.indexOf(viewMu)) * azimuths.length +
          azimuths.indexOf(azimuth)
        const exact = oracle[side][at]!
        expect(Math.abs(row.mean[s]! - exact)).toBeLessThan(
          3 * row.error[s]! + ORACLE * exact,
        )
        checked += 1
      })
    }
    expect(checked).toBeGreaterThanOrEqual(30)
  })
})
