/*
 * The jitter on the GPU: the mask read through the module's own node
 * against the generated bytes, a history pixel's samples against the
 * mask's slices in order, the four numbers of a ray against each other,
 * the default lever against phase 0's draw to the bit, and the trace's
 * bindings with the mask bound.
 *
 * Every number the mask gives is (b + ½)/256 for a byte b, exact in a
 * float32, so a read is compared as a byte, not to a tolerance.
 */

let gpu: GpuSession
let renderer: WebGPURenderer

beforeAll(async () => {
  gpu = await openGpu(8, 8)
  renderer = gpu.renderer
})

afterAll(() => {
  gpu.dispose()
})

const { width: W, height: H, slices: S } = BLUE_NOISE
const bytes = blueNoiseTexels()
const byteAt = (x: number, y: number, z: number): number =>
  bytes[
    (((z % S) + S) % S) * W * H + (((y % H) + H) % H) * W + (((x % W) + W) % W)
  ]!
const asByte = (value: number): number => value * 256 - 0.5
const lever = (
  uniforms: CloudUniforms,
  name: (typeof CLOUD_JITTERS)[number],
) => {
  uniforms.trace.jitter.value = CLOUD_JITTERS.indexOf(name)
}

/** A kernel writing `values(texel)` for every texel of a `width` × `height` grid, four floats each. */
function grid(
  width: number,
  height: number,
  values: (texel: Node<'uvec2'>) => readonly Node<'float'>[],
): {
  readonly read: () => Promise<Float32Array>
  readonly kernel: ComputeNode
  readonly stride: number
} {
  const count = width * height
  const stride = values(uvec2(0, 0)).length
  const out = new StorageBufferAttribute(new Float32Array(count * stride), 1)
  const into = storage(out, 'float', count * stride)
  const kernel = Fn(() => {
    If(instanceIndex.lessThan(uint(count)), () => {
      const texel = uvec2(
        instanceIndex.mod(uint(width)),
        instanceIndex.div(uint(width)),
      )
      values(texel).forEach((value, k) => {
        into.element(instanceIndex.mul(uint(stride)).add(uint(k))).assign(value)
      })
    })
  })().compute(count)
  return {
    kernel,
    stride,
    read: async () => {
      await gpu.compute(kernel)
      return new Float32Array(await gpu.readBuffer(out))
    },
  }
}

/** A ray's four numbers at every texel of a grid, on the frame and phase the uniforms hold. */
function draws(
  jitter: CloudJitter,
  uniforms: CloudUniforms,
  width: number,
  height: number,
) {
  return grid(width, height, (texel) => {
    const draw = jitter.draw(texel, uniforms.trace.frame)
    return [draw.x, draw.y, draw.z, draw.w]
  })
}

function setFrame(uniforms: CloudUniforms, frame: number, phase: number): void {
  const [px, py] = CLOUD_TRACE_PHASES[phase]!
  uniforms.trace.frame.value = frame >>> 0
  uniforms.trace.phase.value.set(px, py)
}

describe('the mask as a resource', () => {
  it('holds nothing until a graph reads it, then its 65,536 bytes as one R8 3D texture, and nothing once disposed', () => {
    const jitter = createCloudJitter({ uniforms: createCloudUniforms() })
    expect(jitter.bytes).toBe(0)
    expect(jitter.textures()).toEqual([])
    jitter.draw(uvec2(0, 0), uint(0))
    expect(jitter.bytes).toBe(64 * 64 * 16)
    const [map] = jitter.textures()
    expect(map).toBeInstanceOf(Data3DTexture)
    expect(jitter.textures()).toHaveLength(1)
    expect(map!.image).toMatchObject({ width: 64, height: 64, depth: 16 })
    expect(map!.format).toBe(RedFormat)
    expect(map!.type).toBe(UnsignedByteType)
    // A second graph reads the one texture through the one node (rule 57).
    jitter.draw(uvec2(1, 1), uint(1))
    expect(jitter.textures()).toEqual([map])
    jitter.dispose()
    expect(jitter.bytes).toBe(0)
    expect(jitter.textures()).toEqual([])
  })
})

describe('the mask’s reads', () => {
  it('are the generated bytes, every texel of every slice, at each of a ray’s four offsets', async () => {
    const uniforms = createCloudUniforms()
    lever(uniforms, 'stbn')
    const jitter = createCloudJitter({ uniforms })
    const run = draws(jitter, uniforms, W, H)
    for (let slice = 0; slice < S; slice += 1) {
      setFrame(uniforms, 4 * slice, 0)
      const values = await run.read()
      for (let y = 0; y < H; y += 1) {
        for (let x = 0; x < W; x += 1) {
          const at = (y * W + x) * 4
          MASK_READS.forEach(([dx, dy], k) => {
            expect(asByte(values[at + k]!)).toBe(byteAt(x + dx, y + dy, slice))
          })
        }
      }
    }
    run.kernel.dispose()
    jitter.dispose()
  })

  it('give a history pixel its eight samples from eight consecutive slices, wrapping with no shift', async () => {
    /*
     * The converging regime: frame n traces phase n mod 4, so a history
     * pixel takes a sample every fourth frame. Thirty-two frames from frame
     * 56 cross the mask's end: slices 14, 15, 0, 1, … 5.
     */
    const uniforms = createCloudUniforms()
    lever(uniforms, 'stbn')
    const jitter = createCloudJitter({ uniforms })
    const size = 16
    const run = draws(jitter, uniforms, size, size)
    const samples = new Map<number, number[]>()
    const first = 56
    for (let n = first; n < first + 32; n += 1) {
      setFrame(uniforms, n, n % 4)
      const [px, py] = CLOUD_TRACE_PHASES[n % 4]!
      const values = await run.read()
      for (let j = 0; j < size; j += 1) {
        for (let i = 0; i < size; i += 1) {
          const pixel = (2 * j + py) * 2 * size + 2 * i + px
          const taken = samples.get(pixel) ?? []
          taken.push(asByte(values[(j * size + i) * 4]!))
          samples.set(pixel, taken)
        }
      }
    }
    expect(samples.size).toBe(4 * size * size)
    for (const [pixel, taken] of samples) {
      const hx = pixel % (2 * size)
      const hy = Math.floor(pixel / (2 * size))
      const [i, j] = [hx >> 1, hy >> 1]
      const [px, py] = [hx & 1, hy & 1]
      const x = i + PHASE_STRIDE * px
      const y = j + PHASE_STRIDE * py
      const start = first >> 2
      expect(taken).toEqual(
        Array.from({ length: 8 }, (_, k) => byteAt(x, y, start + k)),
      )
    }
    run.kernel.dispose()
    jitter.dispose()
  })
})

/** Pearson's correlation of two equal-length samples. */
function correlation(a: readonly number[], b: readonly number[]): number {
  const mean = (v: readonly number[]) => v.reduce((s, x) => s + x, 0) / v.length
  const ma = mean(a)
  const mb = mean(b)
  let ab = 0
  let aa = 0
  let bb = 0
  for (let k = 0; k < a.length; k += 1) {
    ab += (a[k]! - ma) * (b[k]! - mb)
    aa += (a[k]! - ma) ** 2
    bb += (b[k]! - mb) ** 2
  }
  return ab / Math.sqrt(aa * bb)
}

describe('a ray’s numbers', () => {
  /*
   * A 1080p trace is 480 × 270 texels; this one is a third of each side,
   * which holds the mask's 64-texel tile 2.5 times across and leaves a
   * correlation's sampling spread at 1/√14,400, under 0.01.
   */
  const width = 160
  const height = 90
  const frames = [0, 1, 2, 3, 5, 77, 1000, 123_457, 0xffff_fff0]
  const PAIRWISE = 0.05

  async function pairs(name: (typeof CLOUD_JITTERS)[number]) {
    const uniforms = createCloudUniforms()
    lever(uniforms, name)
    const jitter = createCloudJitter({ uniforms })
    const run = draws(jitter, uniforms, width, height)
    const worst = new Map<string, number>()
    for (const frame of frames) {
      setFrame(uniforms, frame, frame % 4)
      const values = await run.read()
      const columns = [0, 1, 2, 3].map((k) =>
        Array.from({ length: width * height }, (_, t) => values[t * 4 + k]!),
      )
      for (let a = 0; a < 4; a += 1) {
        for (let b = a + 1; b < 4; b += 1) {
          const key = 'xyzw'[a]! + 'xyzw'[b]!
          const r = Math.abs(correlation(columns[a]!, columns[b]!))
          worst.set(key, Math.max(worst.get(key) ?? 0, r))
        }
      }
    }
    run.kernel.dispose()
    jitter.dispose()
    return worst
  }

  it('are pairwise uncorrelated over a frame under the mask', async () => {
    const worst = await pairs('stbn')
    expect(worst.size).toBe(6)
    for (const [pair, r] of worst)
      expect([pair, r < PAIRWISE]).toEqual([pair, true])
  })

  it('under the gradient, keep the third number apart from the other three', async () => {
    /*
     * The first step's share and the point inside the pixel are phase 0's
     * draw, kept to the bit (below), and they are not apart: `.x` is read at
     * the texel and `.y` at the history pixel 2·texel + φ, and the gradient
     * at a doubled coordinate is the same hash at twice the frequency. It
     * is measured, not asserted away: the campaign weighs it against the
     * mask (§7.4).
     */
    const worst = await pairs('ign')
    for (const pair of ['xz', 'yz', 'xw', 'yw', 'zw'])
      expect([pair, worst.get(pair)! < PAIRWISE]).toEqual([pair, true])
    expect(worst.get('xy')).toBeGreaterThan(PAIRWISE)
  })
})

describe('the default lever', () => {
  it('draws phase 0’s numbers to the bit: the trace’s at the texel and at its history pixel', async () => {
    const uniforms = createCloudUniforms()
    lever(uniforms, 'ign')
    const jitter = createCloudJitter({ uniforms })
    const frame = uniforms.trace.frame
    const width = 64
    const height = 48
    const run = grid(width, height, (texel) => {
      const draw = jitter.draw(texel, frame)
      const pixel = texel.mul(uint(2)).add(uvec2(uniforms.trace.phase))
      const asBuilt = traceJitter(pixel, frame)
      return [
        draw.x,
        draw.y,
        draw.z,
        traceJitter(texel, frame).x,
        asBuilt.x,
        asBuilt.y,
      ]
    })
    for (const n of [0, 1, 6, 1_600_003, 0x8000_0007, 0xffff_ffff]) {
      for (let phase = 0; phase < 4; phase += 1) {
        setFrame(uniforms, n, phase)
        const bits = new Uint32Array((await run.read()).buffer)
        for (let t = 0; t < width * height; t += 1) {
          const at = t * run.stride
          expect([bits[at], bits[at + 1], bits[at + 2]]).toEqual([
            bits[at + 3],
            bits[at + 4],
            bits[at + 5],
          ])
        }
      }
    }
    run.kernel.dispose()
    jitter.dispose()
  })
})

/** Sampled textures a WGSL program declares, by kind, and its storage textures. */
function census(kernel: ComputeNode) {
  const nodes = (
    renderer as unknown as {
      _nodes: { getForCompute(node: ComputeNode): { computeShader: string } }
    }
  )._nodes
  const wgsl = nodes.getForCompute(kernel).computeShader
  const kinds: Record<string, number> = {}
  let storageCount = 0
  for (const [, kind] of wgsl.matchAll(/var\s+\w+\s*:\s*texture_(\w+)</g)) {
    if (kind!.startsWith('storage')) storageCount += 1
    else kinds[kind!] = (kinds[kind!] ?? 0) + 1
  }
  const sampled = Object.values(kinds).reduce((sum, n) => sum + n, 0)
  return { kinds, sampled, storage: storageCount }
}

describe('the trace with the mask bound', () => {
  /** A 1 × 1 R16F depth copy, filtered as the real one is. */
  function depth(): DataTexture {
    const data = new Uint16Array([DataUtils.toHalfFloat(60_000)])
    const map = new DataTexture(data, 1, 1, RedFormat, HalfFloatType)
    map.magFilter = LinearFilter
    map.minFilter = LinearFilter
    map.needsUpdate = true
    return map
  }

  it('binds one 3D texture more than a trace placed by the gradient alone, 11 sampled of the stage’s 16, and builds', async () => {
    const field = createCloudField()
    const copy = depth()
    const deps = {
      uniforms: field.uniforms,
      medium: field.medium,
      sun: field.sun,
      phase: field.phase,
      far: field.farAtlas.far,
      depth: () => copy,
      sky: field.sky,
      source: field.source,
    }
    // A draw written out of the gradient alone reads no mask: what the
    // lever's branch adds to the trace is the difference of the two.
    const unbound = new CloudTrace({
      ...deps,
      jitter: {
        at: traceJitter,
        draw: (texel, frame) =>
          vec4(
            traceJitter(texel, frame).x,
            traceJitter(
              texel.mul(uint(2)).add(uvec2(field.uniforms.trace.phase)),
              frame,
            ),
            0,
          ),
      },
    })
    const bound = new CloudTrace({ ...deps, jitter: field.jitter })
    try {
      const before = census(unbound.kernels()[0]!)
      expect(field.jitter.bytes).toBe(0)
      const after = census(bound.kernels()[0]!)
      expect(before.sampled).toBe(10)
      expect(after.kinds).toEqual({
        ...before.kinds,
        '3d': before.kinds['3d']! + 1,
      })
      expect(after.sampled).toBe(11)
      expect(after.storage).toBe(4)
      const from = gpu.reported().length
      await bound.warm(renderer)
      expect(
        gpu
          .reported()
          .slice(from)
          .filter((entry) => entry.type === 'error'),
      ).toEqual([])
      expect(field.jitter.bytes).toBe(64 * 64 * 16)
    } finally {
      unbound.dispose()
      bound.dispose()
      field.dispose()
      copy.dispose()
    }
  }, 120_000)

  it('is what the system draws: its trace reads the draw, and its jitter holds the mask', async () => {
    const rig = cloudRig(gpu, 16, 16)
    try {
      await rig.system!.warm()
      const jitter = rig.system!.resources.find(
        (held) => held.name === 'jitter',
      )
      expect(jitter).toBeDefined()
      expect(jitter!.bytes).toBe(64 * 64 * 16)
      expect(jitter!.textures()).toHaveLength(1)
    } finally {
      rig.dispose()
    }
  }, 120_000)
})
