const INDEX: SearchIndex = {
  version: 'test',
  stop: ['the', 'and', 'for'],
  rows: [
    {
      r: '/docs/concepts/frames',
      t: 'Reference frames',
      w: 'concepts',
      k: 'prose',
      l: 'What does "3 m above the pad" mean while the planet orbits?',
      h: [
        ['surface-frames', 'Surface frames and the identity trap'],
        ['the-chain', 'The frame chain'],
      ],
      b: 'above chain frame frames identity orbit pad planet surface trap',
    },
    {
      r: '/docs/concepts/time',
      t: 'Simulation time',
      w: 'concepts',
      k: 'prose',
      l: 'Why 144 Hz produces the same universe as 60 Hz.',
      h: [['the-tick', 'The tick']],
      b: 'clock frame hertz simulation tick time universe',
    },
    {
      r: '/docs/api/spatial/Sector',
      t: 'Sector',
      w: 'api',
      k: 'api-member',
      l: 'One cell of the universe grid.',
      h: [],
      b: 'cell frame grid sector universe',
    },
  ],
}

describe('search', () => {
  it('ignores a term too short to locate anything', () => {
    expect(tokenize('a b')).toEqual([])
    expect(searchDocs(INDEX, 'a')).toEqual([])
  })

  /*
   * The `AND` makes a stop word poison: it is in no page's vocabulary, so a
   * query keeping one requires a term nothing can satisfy. "The frame chain"
   * returned nothing before the index started shipping its own list.
   */
  it('drops the words the index dropped, rather than failing on them', () => {
    expect(tokenize('the frame', INDEX.stop)).toEqual(['frame'])
    expect(searchDocs(INDEX, 'the frame').length).toBeGreaterThan(0)
  })

  it('ranks a title hit above a heading hit above a body hit', () => {
    const hits = searchDocs(INDEX, 'frame')
    expect(hits.map((hit) => hit.title)).toEqual([
      'Reference frames',
      'Simulation time',
      'Sector',
    ])
  })

  /* An `OR` would bury the page about both under every page that mentions
     either, which is the whole reason somebody typed two words. */
  it('requires every term, not any of them', () => {
    expect(searchDocs(INDEX, 'frame trap').map((hit) => hit.title)).toEqual([
      'Reference frames',
    ])
    expect(searchDocs(INDEX, 'frame unicorn')).toEqual([])
  })

  it('links to the section that matched rather than to the top of the page', () => {
    const [hit] = searchDocs(INDEX, 'identity')
    expect(hit?.route).toBe('/docs/concepts/frames#surface-frames')
    expect(hit?.section?.text).toBe('Surface frames and the identity trap')
  })

  it('has no section to offer when the title alone matched', () => {
    const [hit] = searchDocs(INDEX, 'sector')
    expect(hit?.route).toBe('/docs/api/spatial/Sector')
    expect(hit?.section).toBeNull()
  })

  /*
   * The one thing the index cannot represent is adjacency: it knows both words
   * occur on a page, not that they occur together. The raw query still can, and
   * this is where that is spent.
   */
  it('prefers a page whose title is the phrase', () => {
    const hits = searchDocs(INDEX, 'simulation time')
    expect(hits[0]?.title).toBe('Simulation time')
  })

  it('matches the start of a word, not the middle of one', () => {
    expect(searchDocs(INDEX, 'clo').map((hit) => hit.title)).toEqual([
      'Simulation time',
    ])
    expect(searchDocs(INDEX, 'ock')).toEqual([])
  })

  it('honours the limit', () => {
    expect(searchDocs(INDEX, 'frame', 2)).toHaveLength(2)
  })
})
